"""Export aioquic's locked dependency closure with hashes; no resolver or secrets."""

import tomllib
from pathlib import Path

root = Path(__file__).resolve().parents[1]
packages = {
    p["name"]: p for p in tomllib.loads((root / "uv.lock").read_text())["package"]
}
pending, selected = ["aioquic"], set()
while pending:
    name = pending.pop()
    if name in selected:
        continue
    selected.add(name)
    pending.extend(d["name"] for d in packages[name].get("dependencies", []))
lines = ["# Generated by scripts/export_worker_requirements.py from uv.lock."]
for name in sorted(selected):
    package = packages[name]
    hashes = sorted({w["hash"] for w in package.get("wheels", [])})
    if not hashes:
        raise ValueError("binary wheels required")
    lines.append(f"{name}=={package['version']} \\")
    lines.extend(
        "    --hash=" + digest + (" \\" if i < len(hashes) - 1 else "")
        for i, digest in enumerate(hashes)
    )
(root / "worker-requirements.txt").write_text("\n".join(lines) + "\n", encoding="utf-8")
